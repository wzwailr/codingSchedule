import {stat} from 'node:fs/promises';import {createReadStream} from 'node:fs';import {createHash} from 'node:crypto';import {isAbsolute,resolve,dirname,join} from 'node:path';

function samePath(a:string,b:string){return isAbsolute(a)&&isAbsolute(b)&&resolve(a).toLowerCase()===resolve(b).toLowerCase();}
const hashes=new Map<string,string>();
async function fileHash(path:string,info:Awaited<ReturnType<typeof stat>>){const key=[resolve(path),info.size,info.mtimeMs,info.ctimeMs].join(':');const old=hashes.get(key);if(old)return old;const hash=createHash('sha256');for await(const bytes of createReadStream(path,{highWaterMark:65536}))hash.update(bytes);const value=hash.digest('hex');if(hashes.size>=128)hashes.clear();hashes.set(key,value);return value;}
async function sameFile(a:string,b:string){try{if(!isAbsolute(a)||!isAbsolute(b))return false;const [x,y]=await Promise.all([stat(a),stat(b)]);if(!x.isFile()||!y.isFile()||x.size!==y.size)return false;return samePath(a,b)||await fileHash(a,x)===await fileHash(b,y);}catch{return false;}}
// Parse only the quoted argv forms generated by this application. Never run a
// shell to inspect an installed command or interpret arbitrary shell syntax.
function hookArgs(command:unknown,windows=false):string[]|null{
 if(typeof command!=='string')return null;
 let rest=command.trim();if(rest.startsWith('& '))rest=rest.slice(2);
 const args:string[]=[];
 while(rest){const match=windows?/^"([^"]*)"(?:\s+|$)/.exec(rest):/^'((?:[^']|'')*)'(?:\s+|$)/.exec(rest);if(!match)return null;args.push(windows?match[1]!:match[1]!.replaceAll("''","'"));rest=rest.slice(match[0].length);}
 return args;
}
function hookRuntime(command:unknown){
 if(typeof command!=='string')return {command,runAsNode:false};
 const powershell="$env:ELECTRON_RUN_AS_NODE='1'; ",wait=' | Out-String -Stream';
 if(command.startsWith(powershell)&&command.endsWith(wait))return {command:command.slice(powershell.length,-wait.length),runAsNode:true};
 for(const prefix of ['set "ELECTRON_RUN_AS_NODE=1" && ','ELECTRON_RUN_AS_NODE=1 '])if(command.startsWith(prefix))return {command:command.slice(prefix.length),runAsNode:true};
 return {command,runAsNode:false};
}
export async function compatibleEntry(before:unknown,after:unknown,hook:boolean):Promise<boolean>{
 if(!before||!after||typeof before!=='object'||typeof after!=='object')return false;
 const old=before as Record<string,unknown>,next=after as Record<string,unknown>;
 if(old.disabled===true||old.enabled===false)return false;
 if(!hook){
  if(typeof old.command!=='string'||typeof next.command!=='string'||!Array.isArray(old.args)||!Array.isArray(next.args)||old.args.length!==next.args.length)return false;
  const mode=(value:unknown)=>!!value&&typeof value==='object'&&(value as Record<string,unknown>).ELECTRON_RUN_AS_NODE==='1';
  if(mode(old.env)!==mode(next.env))return false;
  if(!await sameFile(old.command,next.command))return false;
  const a:unknown[]=old.args,b:unknown[]=next.args;
  return a.every((arg,i)=>typeof arg==='string'&&(arg===b[i]||i>0&&['--credential','--endpoint'].includes(String(a[i-1]))&&samePath(arg,String(b[i]))));
 }
 if(old.type!=='command'||old.async!==true||old.timeout!==next.timeout||old.shell!==next.shell)return false;
 const oldRuntime=hookRuntime(old.commandWindows??old.command),nextRuntime=hookRuntime(next.commandWindows??next.command);
 if(oldRuntime.runAsNode!==nextRuntime.runAsNode)return false;
 const a=hookArgs(oldRuntime.command,typeof old.commandWindows==='string'),b=hookArgs(nextRuntime.command,typeof next.commandWindows==='string');
 if(!a||!b||a.length!==b.length)return false;
 for(let i=0;i<a.length;i++){
  if(a[i]===b[i])continue;
  if(i>0&&['--credential','--endpoint'].includes(a[i-1]!)&&samePath(a[i]!,b[i]!))continue;
  if(i===0&&await sameFile(a[i]!,b[i]!))continue;
  if(/(?:^|[\\/])(?:codex|claude)\.cjs$/.test(a[i]!)&&await sameFile(a[i]!,b[i]!)&&await sameFile(join(dirname(a[i]!),'common.cjs'),join(dirname(b[i]!),'common.cjs')))continue;
  return false;
 }
 return true;
}
